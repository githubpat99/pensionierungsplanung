const assert=require('node:assert/strict');
const f=require('./retirement-feasibility.js');
const base={today:65,start:65,end:75,capital:100000,bound:0,inflation:0,phases:[{from:0,need:10000}],sources:[],returns:[0,0,0],repair:0};
assert.equal(f.evaluate(base).feasible,true,'exact exhaustion at horizon remains feasible');
const poor=f.evaluate({...base,capital:20000});
assert.equal(poor.capitalAtHorizon,0);
assert.equal(poor.feasible,false,'clamped zero capital must not mask shortfalls');
assert.equal(poor.firstGapAge,67);
assert.equal(f.evaluate({...base,capital:0}).firstGapAge,65);
const recovery=f.evaluate({...base,capital:0,sources:[{amount:20000,from:70}]});
assert.ok(recovery.capitalAtHorizon>0);assert.equal(recovery.feasible,false,'late recovery does not repair earlier gaps');
assert.equal(f.findBestVariant([{firstGapAge:67,totalGap:100,capitalShare:0},{firstGapAge:68,totalGap:200,capitalShare:10}]).capitalShare,10);
assert.equal(f.findBestVariant([{firstGapAge:68,totalGap:100,capitalShare:0},{firstGapAge:68,totalGap:200,capitalShare:10}]).capitalShare,0);
const inputs=[{capitalShare:0,input:{...base,capital:0}},{capitalShare:100,input:base}];
const before=JSON.stringify(inputs),result=f.analyze(inputs);
assert.equal(result.planFeasible,true);assert.equal(JSON.stringify(inputs),before,'comparison does not mutate inputs');
const deficit=f.analyze([{capitalShare:100,input:{...base,capital:80000}}]);
assert.equal(deficit.planFeasible,false);
assert.ok(Math.abs(deficit.annualShortfall-2000)<.5);
assert.ok(Math.abs(deficit.sustainableAnnualNeed-8000)<.5);
assert.equal(f.evaluate(f.reduceNeeds({...base,capital:80000},deficit.annualShortfall)).feasible,true);
const phased={...base,phases:[{from:0,need:20000},{from:70,need:10000}]};
const sustainable=f.sustainableNeed(phased);
assert.ok(Math.abs(sustainable.annualShortfall-5000)<.5);
assert.deepEqual(f.reduceNeeds(phased,15000).phases.map(p=>p.need),[5000,0]);
console.log('Passed: horizon boundary, depletion, recovery, ranking, immutability, sustainable need and phases.');
