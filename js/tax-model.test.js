const assert=require('node:assert/strict');
const tax=require('./tax-model.js');
const {simulate}=require('./retirement-engine.js');
assert.equal(Object.keys(tax.config.cantons).length,26);
for(const [n,level] of [[0,'low'],[80000,'low'],[80001,'medium'],[130000,'medium'],[130001,'high']])assert.equal(tax.getIncomeTaxLevel(n),level);
assert.equal(tax.calculateEstimatedIncomeTax('AR',100000),16500);
assert.equal(tax.calculateCapitalWithdrawalTax('AR',1000000),111400);
assert.equal(tax.calculateCapitalWithdrawalTax('AR',500000),49550);
assert.equal(500000-tax.calculateCapitalWithdrawalTax('AR',500000),450450);
assert.ok(Math.abs(tax.getCapitalWithdrawalTaxRate('AR',750000)-10.525)<1e-10);
assert.equal(tax.getCapitalWithdrawalTaxRate('AR',10000),7.56);
assert.equal(tax.getCapitalWithdrawalTaxRate('AR',2000000),11.14);
assert.equal(tax.calculateCapitalWithdrawalTax('AR',0),0);
assert.equal(tax.calculateEstimatedIncomeTax(null,100000),null);
const base={today:65,start:65,end:68,capital:888600,bound:0,inflation:0,phases:[{from:0,need:100000}],sources:[{amount:60000}],returns:[0,0,0],repair:30000,canton:'AR'};
const r=simulate(base)[0];
assert.equal(r.grossIncome,60000);assert.equal(r.estimatedIncomeTax,8100);assert.equal(r.rent,51900);
assert.equal(r.withdrawal,48100);assert.equal(r.end,840500);
assert.equal(r.buckets.reduce((a,b)=>a+b),888600,'net capital allocated without taxing it again');
assert.equal(simulate({...base,capital:2000000})[0].estimatedIncomeTax,8100,'private capital has no income tax');
assert.equal(simulate({...base,sources:[{amount:100000,taxable:false}]})[0].estimatedIncomeTax,0);
assert.equal(simulate({...base,sources:[{amount:60000,rental:true}]},'property')[0].estimatedIncomeTax,0);
assert.equal(simulate({...base,sources:[{amount:100000,until:66}]})[1].estimatedIncomeTax,0);
const inflated=simulate({...base,inflation:2,sources:[{amount:81000}]});
assert.equal(inflated[1].estimatedIncomeTax,81000*.165/1.02,'nominal income determines bracket');
